"""Generate core/fees.generated.js from core/fees.py.

core/fees.py is the single source of truth for platform fees. This script
exports the fee constants into a plain JS file that index.html loads, so the
SPA and the tested Python logic can never drift apart. Run it after any fee
change:

    python generate_js.py

The test suite asserts that the committed generated file matches the Python
constants (tests/test_generated_sync.py).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from core.fx import FALLBACK_RATES, SYMBOLS
from core.fees import (
    AMAZON_PER_ITEM_FEE,
    AMAZON_REFERRAL,
    EBAY,
    ETSY,
    ETSY_SHIPPING_PRESETS,
    REGULATORY_COUNTRIES,
    SHOPIFY,
    VINTED,
)

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "core" / "fees.generated.js"

PAYLOAD = {
    "ETSY": {
        "listing": ETSY["listing_fee"],
        "transaction": ETSY["transaction_pct"],
        "payPct": ETSY["payment_pct"],
        "payFixed": ETSY["payment_fixed"],
        "offsiteAds": ETSY["offsite_ads_pct"],
        "ads": ETSY["ads_pct"],
        "regulatory": ETSY["regulatory_pct"],
    },
    "SHOPIFY": {"payPct": SHOPIFY["payment_pct"], "payFixed": SHOPIFY["payment_fixed"]},
    "EBAY": {"finalValuePct": EBAY["final_value_pct"], "perOrder": EBAY["per_order_fixed"]},
    "VINTED": {"sellerPct": VINTED["seller_pct"]},
    "AMAZON_REFERRAL": AMAZON_REFERRAL,
    "AMAZON_PER_ITEM": AMAZON_PER_ITEM_FEE,
    "REGULATORY_COUNTRIES": sorted(REGULATORY_COUNTRIES),
    "FX": {"rates": FALLBACK_RATES, "symbols": SYMBOLS},
    "SHIP_PRESETS": {k: {"label": v["label"], "paid": v["paid"], "charged": v["charged"]}
                     for k, v in ETSY_SHIPPING_PRESETS.items()},
}

HEADER = (
    "// AUTO-GENERATED by generate_js.py from core/fees.py — DO NOT EDIT.\n"
    "// Regenerate with: python generate_js.py\n"
    '"use strict";\n'
    "window.ML_FEES = "
)


def build_js() -> str:
    return HEADER + json.dumps(PAYLOAD, indent=2) + ";\n"


def main() -> None:
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != build_js():
            print(f"STALE: {OUT} does not match core/fees.py — run: python generate_js.py")
            sys.exit(1)
        print(f"OK: {OUT} is in sync with core/fees.py")
        return
    OUT.write_text(build_js(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
